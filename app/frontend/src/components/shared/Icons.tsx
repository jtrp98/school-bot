export type IconName = keyof typeof icons;

export function Icon({ name, size = 24, className }: {
  name: IconName | "" | undefined;
  size?: number;
  className?: string;
}) {
  if (!name) return null;
  const IconComponent = icons[name];
  return <IconComponent size={size} className={className ? `icon shrink-0 ${className}` : "icon shrink-0"} aria-hidden="true" focusable="false" />;
}
